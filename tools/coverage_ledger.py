"""Build audit/TEXTBOOK-COVERAGE-LEDGER.md from audit/inventory.json, the three pedagogy reviews (audit/reviews/),
the question ledger and the batch Q draft. python3 tools/coverage_ledger.py"""
import json, re, csv, collections, os
INV = json.load(open('audit/inventory.json'))
scores, finding = {}, {}
for f in ('audit/reviews/pedagogy_ch01-05.md', 'audit/reviews/pedagogy_ch06-10.md', 'audit/reviews/pedagogy_ch11-15.md'):
    for line in open(f):
        c = [x.strip() for x in line.strip().strip('|').split('|')]
        if len(c) >= 4 and re.fullmatch(r'\d{6}', c[1]):
            s = c[2:9] if len(c) >= 10 else c[2].split('/')
            s = [re.sub(r'[^0-9n/a]', '', re.sub(r'\(.*?\)', '', x)) or 'n/a' for x in s]
            scores[c[1]] = '/'.join(s); finding[c[1]] = c[-1]
Q = collections.defaultdict(collections.Counter)
for r in csv.DictReader(open('audit/QUESTION-LEDGER.csv')):
    Q[r['page_id']][r['type']] += 1
    if r['type'] == 'exercise' and r['has_inline_answer'] == '0': Q[r['page_id']]['unanswered'] += 1
B = json.load(open('tools/batchQ_2026-11-13.json'))['edits'] if os.path.exists('tools/batchQ_2026-11-13.json') else {}
sev = lambda notes: min([re.search(r'\bP([0-3])\b', n).group(0) for n in notes if re.search(r'\bP([0-3])\b', n)] or ['P2'])
out = ['# Textbook coverage ledger (master refinement pass, 2026-11-13)', '',
       'One row per live page, in book order. Generated by `tools/coverage_ledger.py`; do not edit by hand.', '',
       '- **PDF pages** are physical pages of the 2026-11-13 16:37 full-book export (1,340 pp.); **print** is the page number printed in the footer.',
       '- **Objectives** = course objective numbers / outline items from the Course Outline Alignment page (597272).',
       '- **Components** = Ex worked examples, Q exercises or problems, Fig images, TI Try It embeds, V videos, VC Valley Connection, Key print answer key.',
       '- **Scores** = accuracy / clarity / prerequisites / visuals / reasoning / practice / transfer, 0-4, from the pedagogy reviews in `audit/reviews/` (visuals judged from alt text and captions only).',
       '- **Correctness** for every page: all problems re-solved on 2026-11-11 and 2026-11-13 (`tools/REVIEW_2026-11-13.md`); this pass did not re-solve them, except the items listed in the errata file.',
       '- **web_checked / pdf_checked**: `script` = automated checks of this pass ran on the page (links, headings, alt text, tables, answer-key parity for web; text scan, tags, footer and page mapping for PDF). `viewed` = a rendered page was looked at. Neither means every pixel was inspected.',
       '- **Batch Q** = number of edits published on LibreTexts on 2026-11-13 with the instructor\'s OK (`tools/batchQ_2026-11-13.json`); every page was read back identical to the planned text.', '',
       '| Section | Page id | PDF pages | Print | Objectives | Components | Scores | Main finding (this pass) | Sev | Batch Q edits (live) | web_checked | pdf_checked | Next action |',
       '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
VIEWED_PDF = {'597094', '597232', '597074'}
for r in INV:
    pid = r['id']; t = r['title']
    comp = []
    for k, lab in (('example', 'Ex'), ('exercise', 'Q')):
        if Q[pid][k]: comp.append(f'{Q[pid][k]} {lab}')
    if r['figures']: comp.append(f"{r['figures']} Fig")
    if r['widgets']: comp.append(f"{len(r['widgets'])} TI")
    if r['videos']: comp.append(f"{len(r['videos'])} V")
    if r['valley']: comp.append('VC')
    if r['print_key']: comp.append('Key')
    notes = [x['note'] for x in B.get(pid, [])]
    f = finding.get(pid, '')
    if Q[pid]['unanswered'] and 'Answer a' not in open(f'pages/live/{pid}.html').read(): f = f"{Q[pid]['unanswered']} exercise(s) had no answer on the page. " + f
    if len(f) > 260: f = f[:257] + '...'
    pdf = f"{r['pdf_start']}-{r['pdf_end']}" if r.get('pdf_start') else 'n/a'
    prn = f"{r.get('print_start', '')}-{r.get('print_end', '')}" if r.get('pdf_start') else 'n/a'
    obj = ', '.join(filter(None, ['obj ' + ','.join(r['objectives_cor']) if r['objectives_cor'] else '', 'unit ' + '; '.join(r['outline_units']) if r['outline_units'] else ''])) or '-'
    nxt = 'recheck in the next full PDF' if notes else ('none' if pid in scores or not re.match(r'\d', t) else 'none')
    out.append(f"| {t} | {pid} | {pdf} | {prn} | {obj} | {', '.join(comp) or '-'} | {scores.get(pid, '-')} | {f.replace('|', '/') or '-'} | {sev(notes) if notes else ('P3' if f else '-')} | {len(notes) or '-'} | script | {'script + viewed' if pid in VIEWED_PDF else ('script' if r.get('pdf_start') else 'n/a')} | {nxt} |")
open('audit/TEXTBOOK-COVERAGE-LEDGER.md', 'w').write('\n'.join(out) + '\n')
print('rows', len(INV), 'scored', len(scores), 'pages with batch Q edits', len(B))
print('unscored numbered pages:', [r['title'][:30] for r in INV if re.match(r'\d', r['title']) and r['id'] not in scores][:40])
